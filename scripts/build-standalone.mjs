import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import react from "@vitejs/plugin-react";
import { build } from "vite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "dist", "standalone-build");
const target = path.join(root, "resume-factory.html");

// Bundle the existing React editor, including its PDF and Word exporters,
// into one JavaScript file before embedding it in a directly openable HTML.
await build({
  configFile: false,
  root,
  base: "./",
  plugins: [react()],
  build: {
    outDir,
    emptyOutDir: true,
    cssCodeSplit: false,
    modulePreload: false,
    assetsInlineLimit: Number.MAX_SAFE_INTEGER,
    rollupOptions: { output: { inlineDynamicImports: true } },
  },
});

const assetsDir = path.join(outDir, "assets");
const assets = await readdir(assetsDir);
const scripts = assets.filter((name) => name.endsWith(".js"));
const styles = assets.filter((name) => name.endsWith(".css"));
if (scripts.length !== 1 || styles.length !== 1 || assets.length !== 2) {
  throw new Error(`Expected one JavaScript and one CSS asset, found: ${assets.join(", ")}`);
}

let html = await readFile(path.join(outDir, "index.html"), "utf8");
const css = (await readFile(path.join(assetsDir, styles[0]), "utf8")).replace(/<\/style/gi, "<\\/style");
const js = (await readFile(path.join(assetsDir, scripts[0]), "utf8")).replace(/<\/script/gi, "<\\/script");
const scriptTag = /<script\b[^>]*\bsrc="\.\/assets\/[^\"]+\.js"[^>]*><\/script>/;
const styleTag = /<link\b[^>]*\bhref="\.\/assets\/[^\"]+\.css"[^>]*>/;
if (!scriptTag.test(html) || !styleTag.test(html)) {
  throw new Error("Vite output changed: cannot find the local JavaScript and CSS references.");
}
// Use replacement callbacks: bundled code contains "$&" and related text,
// which String.replace would otherwise expand into the matched HTML tag.
html = html.replace(styleTag, () => `<style>\n${css}\n</style>`);
html = html.replace(scriptTag, () => `<script type="module">\n${js}\n</script>`);
const inlineScript = html.match(/<script type="module">\n([\s\S]*?)\n<\/script>/);
const inlineStyle = html.match(/<style>\n([\s\S]*?)\n<\/style>/);
if (inlineScript?.[1] !== js || inlineStyle?.[1] !== css) {
  throw new Error("Bundled source changed while embedding it in the HTML.");
}
const markup = html
  .replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, "")
  .replace(/<style\b[^>]*>[\s\S]*?<\/style>/g, "");
if (/<(?:script|link)\b[^>]*(?:src|href)="\.\/assets\//.test(markup) || /<link\b[^>]*rel="modulepreload"/.test(markup)) {
  throw new Error("Standalone HTML still references a build asset.");
}

html = html.replace("<title>", "<!-- Generated by npm run build:standalone; edit src/ instead. -->\n    <title>");
await writeFile(target, html, "utf8");
console.log(`Created ${path.relative(root, target)} (${(Buffer.byteLength(html) / 1024 / 1024).toFixed(2)} MiB)`);
